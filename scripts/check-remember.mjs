import vm from 'node:vm';
import assert from 'node:assert/strict';
import worker from '../worker/index.js';
const html=await (await worker.fetch(new Request('https://test.local/'),{})).text();
const js=html.match(/<script>([\s\S]*?)<\/script>/)[1];
new vm.Script(js);
const fragment=js.slice(js.indexOf('const rememberedConfigKey='),js.indexOf('function refreshModels('));
const ctx=vm.createContext({});vm.runInContext(fragment+';globalThis.read=loadModelConfig;globalThis.write=persistModelConfig;',ctx);
const data=new Map(),storage={getItem:k=>data.get(k)||null,setItem:(k,v)=>data.set(k,v),removeItem:k=>data.delete(k)};
const saved={engine:'deepseek',model:'obsolete',key:'dummy-test-key'};
assert.equal(ctx.read(storage),null);
ctx.write(storage,saved,false);assert.equal(data.size,0);
ctx.write(storage,saved,true);assert.equal(ctx.read(storage).model,'deepseek-flash');assert.equal(ctx.read(storage).key,saved.key);
ctx.write(storage,saved,false);assert.equal(ctx.read(storage),null);
ctx.write(storage,{engine:'doubao',model:'ep-test',key:'dummy-test-key'},true);assert.equal(ctx.read(storage).model,'ep-test');
ctx.write(storage,{engine:'demo'},true);assert.equal(data.size,0);
storage.setItem('nomi.model-config.v1','invalid json');assert.equal(ctx.read(storage),null);
storage.setItem('nomi.model-config.v1',JSON.stringify({engine:'other',key:'key',model:'model'}));assert.equal(ctx.read(storage),null);
assert.equal(ctx.read({getItem(){throw Error('storage blocked')}}),null);
assert.throws(()=>ctx.write({setItem(){throw Error('quota')}},saved,true));
assert(html.includes('id="rememberKey"'));assert(html.includes('id="forgetKey"'));assert(!html.includes('dummy-test-key'));
console.log('Remembered configuration: opt-in, restore, provider validation, fixed model ID, removal, corrupt/blocked storage passed.');
